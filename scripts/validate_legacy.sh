#!/usr/bin/env bash
# SPDX-License-Identifier: BSD-3-Clause
# Validates every legacy input with pd_validate (double and exact kernels) and
# writes the report to data/legacy/VALIDATION.txt.
#   usage: scripts/validate_legacy.sh [BUILD_DIR]   (default build/gcc-release)
set -uo pipefail
cd "$(dirname "$0")/.."
bin="${1:-build/gcc-release}/pd_validate"
[ -x "${bin}" ] || { echo "missing ${bin}; build first" >&2; exit 2; }
out=data/legacy/VALIDATION.txt
L=data/legacy

{
  echo "# Legacy input validation (pd_validate, generated by scripts/validate_legacy.sh)"
  echo "# Plane: OBJ file (X, Z). IN CLASS = simple outer ring; simple, pairwise-disjoint,"
  echo "# non-nested holes inside it."
  echo
  echo "## Hole-elimination inputs (outer ring + holes)"
  "${bin}" --outer ${L}/compgon/cpolygon0.obj $(for i in 0 1 2 3 4 5 6; do echo --hole ${L}/compgon/hole0-${i}.obj; done)
  for d in ${L}/compgon/test*/; do
    outer=$(ls "${d}"p*.obj)
    holes=$(for h in "${d}"h*.obj; do echo --hole "${h}"; done)
    "${bin}" --outer "${outer}" ${holes}
  done
  echo
  echo "## Convex-decomposition inputs (single rings)"
  for f in ${L}/simp/*.obj; do
    [ "$(basename "${f}")" = ctest1.obj ] && continue
    "${bin}" --outer "${f}" 2>&1
  done
  echo
  echo "## Multi-ring file (largest ring = outer, the others = holes)"
  "${bin}" --multi ${L}/simp/ctest1.obj 2>&1
} > "${out}" 2>&1
echo "wrote ${out}"
{ grep -c "exact : IN CLASS" "${out}" || true; } | sed 's/^/in class (exact): /'
{ grep -c "exact : OUT OF CLASS" "${out}" || true; } | sed 's/^/out of class (exact): /'
{ grep -c "^error" "${out}" || true; } | sed 's/^/read errors: /'
